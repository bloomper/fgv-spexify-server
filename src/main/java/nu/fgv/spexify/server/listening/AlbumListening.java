package nu.fgv.spexify.server.listening;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;
import org.jspecify.annotations.Nullable;

import java.time.Instant;

/**
 * What a user has done with a album, as Navidrome has it: their rating, whether they like it.
 *
 * @author Anders Jacobsson
 * @since 1.0
 */
@Entity
@Table(name = "album_listening")
@Getter
@Setter
public class AlbumListening {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "user_id", nullable = false)
    private Long userId;

    @Column(name = "album_id", nullable = false)
    private Long albumId;

    /**
     * 1 to 5, or null when not rated.
     */
    @Column(name = "rating")
    private @Nullable Integer rating;

    @Column(name = "liked_at")
    private @Nullable Instant likedAt;
}
